CREATE TABLE OMS_MODULES (
    MODULE_NAME VARCHAR2(20) NOT NULL,
    DESCRIPTION VARCHAR2(100),
    MODULE_TYPE VARCHAR2(10),
    PRINT_FORMAT_CODE VARCHAR2(12),
    PREVIEW_FLAG VARCHAR2(1) DEFAULT 'N',
    DEFAULT_COPY NUMBER(3,0),
    APPLN_CODE VARCHAR2(40),
    HELP_DIRECTORY VARCHAR2(240),
    CREATE_DATETIME TIMESTAMP DEFAULT systimestamp NOT NULL,
    CREATE_USER_ID VARCHAR2(32) DEFAULT USER NOT NULL,
    MODIFY_DATETIME TIMESTAMP,
    MODIFY_USER_ID VARCHAR2(32),
    AUDIT_TIMESTAMP TIMESTAMP,
    AUDIT_USER_ID VARCHAR2(32),
    AUDIT_MODULE_NAME VARCHAR2(65),
    AUDIT_CLIENT_USER_ID VARCHAR2(64),
    AUDIT_CLIENT_IP_ADDRESS VARCHAR2(39),
    AUDIT_CLIENT_WORKSTATION_NAME VARCHAR2(64),
    AUDIT_ADDITIONAL_INFO VARCHAR2(256),
    CALL_FORM VARCHAR2(1) DEFAULT 'N',
    CONSTRAINT OMS_MOD_PK PRIMARY KEY (MODULE_NAME)
);

CREATE INDEX OMS_MODULES_NI1 ON OMS_MODULES (APPLN_CODE, MODULE_TYPE);
CREATE INDEX OMS_MODULES_X01 ON OMS_MODULES (MODULE_NAME, APPLN_CODE);
